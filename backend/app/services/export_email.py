"""
Gmail & Email Export Service.
Builds pre-filled Gmail Web Compose URLs and optionally sends rich HTML
reports with CSV attachments directly via SMTP (smtp.gmail.com).
"""

import csv
import html
import io
import smtplib
import urllib.parse
from email.mime.application import MIMEApplication
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Any, Dict, List, Optional

from app.config import settings


def rows_to_csv_bytes(columns: List[str], rows: List[Dict[str, Any]]) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf)
    if columns:
        writer.writerow(columns)
        for r in rows:
            writer.writerow([r.get(c, "") for c in columns])
    return buf.getvalue().encode("utf-8")


def format_plain_report(
    title: str,
    note: str = "",
    insight: str = "",
    sql: str = "",
    columns: Optional[List[str]] = None,
    rows: Optional[List[Dict[str, Any]]] = None,
    max_rows: int = 15,
) -> str:
    sections: List[str] = []
    if note:
        sections.append(note.strip())
    if insight:
        sections.append(f"AI Insight:\n{insight.strip()}")
    if sql:
        sections.append(f"SQL Query:\n{sql.strip()}")
    if columns and rows:
        preview = rows[:max_rows]
        lines = [" | ".join(columns), "-" * min(72, len(" | ".join(columns)))]
        for r in preview:
            lines.append(" | ".join(str(r.get(c, ""))[:40] for c in columns))
        if len(rows) > max_rows:
            lines.append(f"... ({len(rows) - max_rows} more rows in attached CSV)")
        sections.append(f"Results ({len(rows)} rows):\n" + "\n".join(lines))
    return f"{title}\n" + "=" * len(title) + "\n\n" + "\n\n".join(sections)


def format_html_report(
    title: str,
    note: str = "",
    insight: str = "",
    sql: str = "",
    columns: Optional[List[str]] = None,
    rows: Optional[List[Dict[str, Any]]] = None,
    max_rows: int = 25,
) -> str:
    parts = [
        '<div style="font-family: -apple-system, BlinkMacSystemFont, Segoe UI, sans-serif; color: #0f172a; max-width: 720px;">',
        f'<h2 style="color: #4f46e5; margin-bottom: 8px;">{html.escape(title)}</h2>',
    ]
    if note:
        parts.append(f'<p style="font-size: 14px; line-height: 1.5;">{html.escape(note)}</p>')
    if insight:
        parts.append(
            '<div style="background: #f8fafc; border-left: 4px solid #4f46e5; padding: 12px; margin: 12px 0; border-radius: 6px;">'
            f'<strong>Insight:</strong> {html.escape(insight)}'
            "</div>"
        )
    if sql:
        parts.append(
            '<div style="background: #0f172a; color: #6ee7b7; padding: 12px; border-radius: 8px; font-family: monospace; font-size: 12px; white-space: pre-wrap; margin: 12px 0;">'
            f"{html.escape(sql)}"
            "</div>"
        )
    if columns and rows:
        parts.append('<table style="border-collapse: collapse; width: 100%; font-size: 12px; margin-top: 12px;">')
        parts.append("<thead><tr>")
        for c in columns:
            parts.append(
                f'<th style="text-align: left; padding: 8px; border-bottom: 2px solid #e2e8f0; background: #f1f5f9;">{html.escape(str(c))}</th>'
            )
        parts.append("</tr></thead><tbody>")
        for r in rows[:max_rows]:
            parts.append("<tr>")
            for c in columns:
                val = str(r.get(c, ""))[:120]
                parts.append(f'<td style="padding: 6px 8px; border-bottom: 1px solid #e2e8f0;">{html.escape(val)}</td>')
            parts.append("</tr>")
        parts.append("</tbody></table>")
        if len(rows) > max_rows:
            parts.append(f'<p style="font-size: 11px; color: #64748b;">Showing first {max_rows} of {len(rows)} rows. Full data is attached as CSV.</p>')
    parts.append('<p style="font-size: 11px; color: #94a3b8; margin-top: 16px;">Generated by SchemaSense Analytics</p>')
    parts.append("</div>")
    return "".join(parts)


def build_gmail_compose_url(to: str, subject: str, body_text: str) -> str:
    params = {
        "view": "cm",
        "fs": "1",
        "su": subject,
        "body": body_text[:1750],
    }
    if to.strip():
        params["to"] = to.strip()
    return "https://mail.google.com/mail/?" + urllib.parse.urlencode(params)


class EmailExportService:
    @staticmethod
    def is_smtp_configured() -> bool:
        return bool(settings.SMTP_USER and settings.SMTP_PASSWORD)

    @staticmethod
    def export_email(
        to: str,
        subject: str,
        note: str = "",
        insight: str = "",
        sql: str = "",
        columns: Optional[List[str]] = None,
        rows: Optional[List[Dict[str, Any]]] = None,
        attachment_filename: str = "schemasense_report.csv",
        send_direct: bool = False,
    ) -> Dict[str, Any]:
        plain_body = format_plain_report(subject, note, insight, sql, columns, rows)
        gmail_url = build_gmail_compose_url(to, subject, plain_body)

        if not send_direct:
            return {
                "sent": False,
                "mode": "gmail_web",
                "gmail_compose_url": gmail_url,
                "plain_report": plain_body,
                "smtp_configured": EmailExportService.is_smtp_configured(),
            }

        if not EmailExportService.is_smtp_configured():
            return {
                "sent": False,
                "smtp_configured": False,
                "gmail_compose_url": gmail_url,
                "plain_report": plain_body,
                "error": "Gmail SMTP is not configured in Settings yet. Use 'Open in Gmail' or configure your Gmail App Password in AI Models & Integrations.",
            }

        if not to.strip():
            raise ValueError("Recipient email address ('To') is required for direct send.")

        msg = MIMEMultipart("mixed")
        msg["Subject"] = subject
        msg["From"] = settings.SMTP_USER
        msg["To"] = to.strip()

        alt_part = MIMEMultipart("alternative")
        alt_part.attach(MIMEText(plain_body, "plain", "utf-8"))
        html_body = format_html_report(subject, note, insight, sql, columns, rows)
        alt_part.attach(MIMEText(html_body, "html", "utf-8"))
        msg.attach(alt_part)

        if columns and rows:
            csv_bytes = rows_to_csv_bytes(columns, rows)
            att = MIMEApplication(csv_bytes, _subtype="csv")
            safe_fname = attachment_filename if attachment_filename.endswith(".csv") else f"{attachment_filename}.csv"
            att.add_header("Content-Disposition", "attachment", filename=safe_fname)
            msg.attach(att)

        with smtplib.SMTP(settings.SMTP_HOST, int(settings.SMTP_PORT), timeout=15) as server:
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
            server.sendmail(settings.SMTP_USER, [to.strip()], msg.as_string())

        return {
            "sent": True,
            "mode": "smtp",
            "to": to.strip(),
            "subject": subject,
            "smtp_configured": True,
        }


email_export_service = EmailExportService()

